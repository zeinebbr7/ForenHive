import React, { useState, useEffect, useCallback } from 'react';
import {
  ResponsiveContainer, BarChart, Bar, XAxis, YAxis, CartesianGrid,
  Tooltip, Legend, PieChart, Pie, Cell,
} from 'recharts';
import api from '../api';
import { fmt, flag } from '../utils';
import { RISK_CRITICAL, RISK_HIGH } from '../constants';

const SEV_COLORS = {
  critical: '#ff5050',
  high:     '#ff9933',
  medium:   '#f59e0b',
  low:      '#2dd4bf',
};
const SEV_ORDER  = ['low', 'medium', 'high', 'critical'];
const SEV_LABELS = { critical: 'Critical', high: 'High', medium: 'Medium', low: 'Low' };

const TOOLTIP_STYLE = {
  backgroundColor: '#0d111e',
  border: '1px solid #1e2538',
  borderRadius: '6px',
  fontFamily: "'JetBrains Mono', monospace",
  fontSize: '11px',
  color: '#e0e6f0',
};
const AXIS_TICK = { fontSize: 10, fill: '#8892a4', fontFamily: "'JetBrains Mono', monospace" };

function SevBadge({ sev }) {
  const s = (sev || '').toUpperCase();
  if (s === 'CRITICAL') return <span className="badge red"> CRITICAL</span>;
  if (s === 'HIGH')     return <span className="badge gold"> HIGH</span>;
  if (s === 'MEDIUM')   return <span className="badge blue"> MEDIUM</span>;
  if (s === 'LOW')      return <span className="badge teal"> LOW</span>;
  return <span className="badge gray">{s || '—'}</span>;
}

export default function Alerts() {
  const [items, setItems] = useState([]);
  const [error, setError] = useState(null);
  const [loading, setLoading] = useState(true);
  const [lastUpdated, setLastUpdated] = useState(null);

  const REFRESH_INTERVAL = 30000;

  const fetchAlerts = useCallback(async () => {
    setLoading(true);
    setError(null);
    try {
      const res = await api.alertHistory({ limit: 500 });
      setItems(Array.isArray(res) ? res : (res.items || []));
    } catch (e) {
      setError(e);
    } finally {
      setLoading(false);
      setLastUpdated(new Date());
    }
  }, []);

  useEffect(() => {
    fetchAlerts();
    const timer = setInterval(fetchAlerts, REFRESH_INTERVAL);
    return () => clearInterval(timer);
  }, [fetchAlerts]);

  /* Derived stats */
  const dayAgo = Date.now() - 86400000;
  const bySev = { critical: 0, high: 0, medium: 0, low: 0 };
  let last24 = 0;
  items.forEach(a => {
    const s = (a.severity || 'low').toLowerCase();
    if (s in bySev) bySev[s]++;
    if (+new Date(a.timestamp || 0) > dayAgo) last24++;
  });
  const sevTotal = items.length || 1;

  const sevData = ['critical', 'high', 'medium', 'low'].map(k => ({
    name:  SEV_LABELS[k],
    value: bySev[k],
    color: SEV_COLORS[k],
  }));

  /* Timeline: last 14 days */
  const dayLabels = [];
  const dayMap = {};
  for (let i = 13; i >= 0; i--) {
    const d   = new Date(Date.now() - i * 86400000);
    const key = d.toISOString().slice(0, 10);
    const lbl = (d.getMonth() + 1) + '/' + d.getDate();
    dayLabels.push({ key, lbl });
    dayMap[key] = { date: lbl, critical: 0, high: 0, medium: 0, low: 0 };
  }
  items.forEach(a => {
    const day = (a.timestamp || '').slice(0, 10);
    if (dayMap[day]) {
      const s = (a.severity || 'low').toLowerCase();
      if (s in dayMap[day]) dayMap[day][s]++;
    }
  });
  const timelineData = dayLabels.map(({ key }) => dayMap[key]);

  /* Top IPs */
  const byIp = {};
  const sevRank = { critical: 4, high: 3, medium: 2, low: 1 };
  items.forEach(a => {
    const ip = a.source_ip;
    if (!ip) return;
    if (!byIp[ip]) byIp[ip] = { count: 0, maxSev: 'low', country: a.country };
    byIp[ip].count++;
    const s = (a.severity || 'low').toLowerCase();
    if ((sevRank[s] || 0) > (sevRank[byIp[ip].maxSev] || 0)) byIp[ip].maxSev = s;
    if (!byIp[ip].country && a.country) byIp[ip].country = a.country;
  });
  const topIpsData = Object.entries(byIp)
    .sort((a, b) => b[1].count - a[1].count)
    .slice(0, 8)
    .map(([ip, d]) => ({
      ip:    (d.country ? flag(d.country) + ' ' : '') + ip,
      count: d.count,
      color: SEV_COLORS[d.maxSev] || '#8892a4',
    }));

  /* Top MITRE */
  const mitreCount = {};
  items.forEach(a => {
    (a.mitre_tags || []).forEach(t => {
      mitreCount[t] = (mitreCount[t] || 0) + 1;
    });
  });
  const topMitre = Object.entries(mitreCount)
    .sort((a, b) => b[1] - a[1])
    .slice(0, 8)
    .map(([id, count]) => ({ id, count }));

  const noData = items.length === 0;
  const noDataMsg = (
    <div className="alert info" style={{ marginTop: 12 }}>
      No alerts yet — will populate once the forensic engine scores sessions ≥ 60 (HIGH / CRITICAL).
    </div>
  );

  return (
    <div>
      <div className="page-head">
        <div>
          <div className="section-tag" style={{ marginBottom: 8 }}>Monitoring</div>
          <h2 className="page-title">Alerts <span>/ Incidents</span></h2>
          <div className="page-sub">
            Alerts generated by the ForenHive engine ·{' '}
            <span>{items.length}</span> total ·{' '}
            <span>{bySev.critical}</span> critical
            {lastUpdated && <> · updated {lastUpdated.toLocaleTimeString()}</>}
          </div>
        </div>
        <div className="page-actions">
          <button className="btn btn-gh btn-sm" onClick={fetchAlerts} disabled={loading}>
            {loading ? 'Loading…' : 'Refresh'}
          </button>
        </div>
      </div>

      {loading && <div className="alert info" style={{ margin: '20px 0' }}>Loading alerts…</div>}
      {error && <div className="alert err">Failed to load alerts: {error.message}</div>}
      {!loading && !error && (
        <div>
          {/* KPI Row */}
          <div className="al-kpi-row">
            <div className="al-kpi" style={{ borderColor: '#ff505044' }}>
              <div className="al-kpi-label">Critical</div>
              <div className="al-kpi-val" style={{ color: '#ff5050' }}>{bySev.critical}</div>
              <div className="al-kpi-sub">immediate priority</div>
            </div>
            <div className="al-kpi" style={{ borderColor: '#ff993344' }}>
              <div className="al-kpi-label">High</div>
              <div className="al-kpi-val" style={{ color: '#ff9933' }}>{bySev.high}</div>
              <div className="al-kpi-sub">to analyze</div>
            </div>
            <div className="al-kpi" style={{ borderColor: '#2dd4bf44' }}>
              <div className="al-kpi-label">Medium / Low</div>
              <div className="al-kpi-val" style={{ color: '#2dd4bf' }}>{bySev.medium + bySev.low}</div>
              <div className="al-kpi-sub">monitoring</div>
            </div>
            <div className="al-kpi" style={{ borderColor: 'var(--border2, var(--border))' }}>
              <div className="al-kpi-label">Last 24h</div>
              <div className="al-kpi-val" style={{ color: 'var(--gold)' }}>{last24}</div>
              <div className="al-kpi-sub">recent activity</div>
            </div>
          </div>

          {/* Charts row 1: Severity + Timeline */}
          <div className="al-grid-2" style={{ marginBottom: 14 }}>
            {/* Severity Breakdown */}
            <div className="al-chart-card" style={{ marginBottom: 0 }}>
              <div className="al-chart-title">Severity Breakdown</div>
              <div className="al-chart-sub">Distribution by priority level</div>
              {noData ? noDataMsg : (
                <div className="al-split-wrap">
                  <PieChart width={160} height={160}>
                    <Pie
                      data={sevData}
                      dataKey="value"
                      nameKey="name"
                      cx={75}
                      cy={75}
                      innerRadius={46}
                      outerRadius={68}
                      paddingAngle={2}
                    >
                      {sevData.map((e, i) => (
                        <Cell key={i} fill={e.color + 'cc'} stroke={e.color} strokeWidth={1} />
                      ))}
                    </Pie>
                    <Tooltip contentStyle={TOOLTIP_STYLE} />
                  </PieChart>
                  <div className="al-legend" style={{ flex: 1 }}>
                    {sevData.map((e, i) => (
                      <div key={i} className="al-legend-row">
                        <span className="al-legend-dot" style={{ background: e.color }} />
                        <span className="al-legend-label">{e.name}</span>
                        <span className="al-legend-val">
                          {e.value} ({((e.value / sevTotal) * 100).toFixed(0)}%)
                        </span>
                      </div>
                    ))}
                  </div>
                </div>
              )}
            </div>

            {/* Timeline */}
            <div className="al-chart-card" style={{ marginBottom: 0 }}>
              <div className="al-chart-title">Alerts Over Time</div>
              <div className="al-chart-sub">Last 14 days · stacked by severity</div>
              {noData ? noDataMsg : (
                <ResponsiveContainer width="100%" height={200}>
                  <BarChart data={timelineData} margin={{ top: 4, right: 8, bottom: 0, left: -10 }}>
                    <CartesianGrid strokeDasharray="3 3" stroke="rgba(255,255,255,0.05)" vertical={false} />
                    <XAxis dataKey="date" tick={AXIS_TICK} tickLine={false} axisLine={false} />
                    <YAxis tick={AXIS_TICK} tickLine={false} axisLine={false} allowDecimals={false} />
                    <Tooltip contentStyle={TOOLTIP_STYLE} />
                    <Legend iconSize={8} wrapperStyle={{ fontSize: '11px', fontFamily: "'JetBrains Mono', monospace", paddingTop: '8px' }} />
                    {SEV_ORDER.map((k, idx) => (
                      <Bar
                        key={k}
                        dataKey={k}
                        stackId="a"
                        fill={SEV_COLORS[k] + 'cc'}
                        stroke={SEV_COLORS[k]}
                        strokeWidth={1}
                        name={SEV_LABELS[k]}
                        radius={idx === SEV_ORDER.length - 1 ? [2, 2, 0, 0] : [0, 0, 0, 0]}
                      />
                    ))}
                  </BarChart>
                </ResponsiveContainer>
              )}
            </div>
          </div>

          {/* Charts row 2: Top IPs + MITRE */}
          <div className="al-grid-2" style={{ marginBottom: 14 }}>
            {/* Top IPs */}
            <div className="al-chart-card" style={{ marginBottom: 0 }}>
              <div className="al-chart-title">Top Offending IPs</div>
              <div className="al-chart-sub">IPs with the most triggered alerts</div>
              {topIpsData.length === 0 ? noDataMsg : (
                <ResponsiveContainer width="100%" height={Math.max(160, topIpsData.length * 30 + 20)}>
                  <BarChart data={topIpsData} layout="vertical" margin={{ top: 0, right: 20, bottom: 0, left: 0 }}>
                    <CartesianGrid strokeDasharray="3 3" stroke="rgba(255,255,255,0.05)" horizontal={false} />
                    <XAxis type="number" tick={AXIS_TICK} tickLine={false} axisLine={false} allowDecimals={false} />
                    <YAxis
                      type="category"
                      dataKey="ip"
                      width={165}
                      tick={{ ...AXIS_TICK, fill: '#e0e6f0' }}
                      tickLine={false}
                      axisLine={false}
                    />
                    <Tooltip contentStyle={TOOLTIP_STYLE} formatter={v => [v + ' alerts', 'Count']} />
                    <Bar dataKey="count" name="Alerts" radius={[0, 3, 3, 0]} barSize={16}>
                      {topIpsData.map((e, i) => (
                        <Cell key={i} fill={e.color + 'bb'} />
                      ))}
                    </Bar>
                  </BarChart>
                </ResponsiveContainer>
              )}
            </div>

            {/* MITRE Techniques */}
            <div className="al-chart-card" style={{ marginBottom: 0 }}>
              <div className="al-chart-title">Top MITRE Techniques</div>
              <div className="al-chart-sub">Most frequent ATT&amp;CK IDs across all alerts</div>
              {topMitre.length === 0 ? noDataMsg : (
                <ResponsiveContainer width="100%" height={Math.max(160, topMitre.length * 30 + 20)}>
                  <BarChart data={topMitre} layout="vertical" margin={{ top: 0, right: 20, bottom: 0, left: 0 }}>
                    <CartesianGrid strokeDasharray="3 3" stroke="rgba(255,255,255,0.05)" horizontal={false} />
                    <XAxis type="number" tick={AXIS_TICK} tickLine={false} axisLine={false} allowDecimals={false} />
                    <YAxis
                      type="category"
                      dataKey="id"
                      width={110}
                      tick={{ ...AXIS_TICK, fill: '#b464ff' }}
                      tickLine={false}
                      axisLine={false}
                    />
                    <Tooltip contentStyle={TOOLTIP_STYLE} formatter={v => [v + ' alerts', 'Count']} />
                    <Bar dataKey="count" name="Alerts" radius={[0, 3, 3, 0]} barSize={16} fill="#b464ffbb" />
                  </BarChart>
                </ResponsiveContainer>
              )}
            </div>
          </div>

          {/* Alert History Table */}
          <div className="al-table-card">
            <div className="al-chart-title" style={{ marginBottom: 12 }}>Alert History</div>
            {items.length === 0 ? (
              <div className="alert info">
                <b>No alerts recorded.</b><br />
                Alerts appear when the forensic engine detects sessions with risk score ≥ 60.
              </div>
            ) : (
              <table className="tbl">
                <thead>
                  <tr>
                    <th style={{ width: 90 }}>Level</th>
                    <th>Threat type</th>
                    <th>Source IP</th>
                    <th>Honeypot</th>
                    <th>Score</th>
                    <th>MITRE</th>
                    <th>Date</th>
                    <th>Email</th>
                  </tr>
                </thead>
                <tbody>
                  {items.slice(0, 100).map((a, i) => (
                    <tr key={a.id || i}>
                      <td><SevBadge sev={a.severity} /></td>
                      <td><b>{a.threat_type || '—'}</b></td>
                      <td className="mono" style={{ fontSize: 11 }}>
                        {a.country ? flag(a.country) + ' ' : ''}{a.source_ip || '—'}
                      </td>
                      <td>{a.honeypot || '—'}</td>
                      <td>
                        <span style={{
                          fontFamily: "'JetBrains Mono', monospace",
                          fontSize: 12,
                          fontWeight: 700,
                          color: a.risk_score >= RISK_CRITICAL ? '#ff5050'
                               : a.risk_score >= RISK_HIGH ? '#ff9933'
                               : '#8892a4',
                        }}>
                          {a.risk_score ?? '—'}
                        </span>
                      </td>
                      <td style={{ fontSize: 10, fontFamily: "'JetBrains Mono', monospace", color: '#b464ff' }}>
                        {(a.mitre_tags || []).slice(0, 3).join(', ') || '—'}
                      </td>
                      <td className="mono" style={{ fontSize: 11 }}>{fmt.date(a.timestamp)}</td>
                      <td>
                        <span className={`badge ${a.dispatched ? 'teal' : 'gray'}`}>
                          {a.dispatched ? 'Sent' : 'Pending'}
                        </span>
                      </td>
                    </tr>
                  ))}
                </tbody>
              </table>
            )}
          </div>
        </div>
      )}
    </div>
  );
}
