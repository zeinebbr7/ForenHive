/* Risk-score thresholds — mirror of forensic-engine/risk_thresholds.py (v2.0.0).
   Keep both files in sync if cutoffs change. */
export const RISK_CRITICAL = 70;  // was 80 in v1
export const RISK_HIGH     = 45;  // was 60 in v1
export const RISK_MEDIUM   = 25;  // was 40 in v1
export const RISK_LOW      = 10;  // was 20 in v1

export function riskLevel(score) {
  const s = Number(score) || 0;
  if (s >= RISK_CRITICAL) return 'CRITICAL';
  if (s >= RISK_HIGH)     return 'HIGH';
  if (s >= RISK_MEDIUM)   return 'MEDIUM';
  if (s >= RISK_LOW)      return 'LOW';
  return 'INFO';
}

